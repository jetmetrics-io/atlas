#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Миграция 010 — поле «Она же» (synonyms) у 23 новых карточек дерева LTV.

    python3 010_sinonimy_ltv.py <путь к atlas.db> [--check]

Зачем. Карточки дерева LTV (mid 928–955) ушли в бой 26.09.2026 с пустым полем «Она же»
у 23 из 28. У всех 873 старых метрик оно заполнено. Дмитрий в тот же день, глядя на
карточку 294 («Она же: Себестоимость обработки заказа»): «Ты его не заводил для новых
карточек?» Синонимы предлагали только на шаге определений и только для пяти карточек,
а приёмка с «Синонимы: —» сверку с нормой Атласа не прошла.

Синонимы подобраны по правилам `site-state/atlas/RULES.md`, раздел «Синонимы», и
проверены двумя способами по просьбе Дмитрия: «чтобы синонимы были релевантные и
не совпадали с названиями других метрик».

  1. Совпадения — по леммам, с именами всех 901 метрики, с 878 синонимами и между собой,
     в том числе с точностью до слов одного ряда (затраты/стоимость/расходы/цена,
     клиент/покупатель/аккаунт). Тревог ноль. Первый вариант 932 «Затраты поддержки
     на одного клиента» почти совпал с 271 «Расходы на поддержку клиентов» — заменён.
  2. Слепой обратный поиск по текстам всех карточек: куда ведёт синоним, если не знать
     ответа. Первый вариант 931 «Затраты на работу продукта у одного клиента» уводил
     к 933, «Затраты на обработку обращений» — к 258 и 294. Заменены.

Пять заполненных раньше (928, 929, 930, 941, 952) не трогаются.

Правка пишет синоним, только если поле пустое. Стоит тот же синоним — пропуск, поэтому
повторный запуск ничего не портит. Стоит другой — миграция останавливается и ничего
не пишет: значит, поле заполнили после сборки и его надо сверить заново.

Синонимы с причинами и следом проверок: `design/trees_ltv/карточки/09_на_приёмку_синонимы.md`.
"""
import sys, re, sqlite3, shutil, pathlib, datetime

# mid → синоним («Она же»)
SINONIMY = {
    931: "Затраты на серверы и сервисы в пересчёте на клиента",
    932: "Затраты на ответы одному клиенту",
    933: "Затраты на плановую работу с одним клиентом",
    934: "Месячная регулярная выручка на клиента",
    935: "Доля новых клиентов, получивших пользу от продукта",
    936: "Дней использования продукта в месяц",
    937: "Ключевых функций, задействованных клиентом за месяц",
    938: "Доля довольных продуктом клиентов",
    939: "Удержание на второй месяц",
    940: "Удержание от месяца X до месяца Y",
    942: "Доля выручки, уходящая на проданный товар",
    943: "Убыток на доставке одного заказа",
    944: "Доля выручки, уходящая на приём оплаты",
    945: "Затраты на возвраты и невыкуп в пересчёте на заказ",
    946: "Затраты на ответы покупателям в пересчёте на заказ",
    947: "Заказов покупателя в месяц с учётом пауз",
    948: "Визитов покупателя в месяц с учётом пауз",
    949: "Заказов на сто визитов",
    950: "Выкупаемость заказов",
    951: "Доля покупателей, доступных для рассылок",
    953: "Доля ушедших постоянных покупателей",
    954: "Доля положительных оценок заказов",
    955: "Доля покупателей с картой лояльности",
}


def norm(s):
    return re.sub(r"\s+", " ", (s or "").lower().replace("ё", "е")).strip()


def primenit(con):
    """Сначала сверяет все поля, потом пишет. Возвращает отчёт строками."""
    plan = []
    for mid, s in SINONIMY.items():
        r = con.execute("select synonyms from metric where id=?", (mid,)).fetchone()
        if not r:
            sys.exit(f"✖ mid {mid} нет в базе")
        if r[0] == s:
            continue
        if r[0] and r[0].strip():
            sys.exit(f"✖ mid {mid}: «Она же» уже «{r[0]}», ждали пустое — ничего не пишу")
        plan.append((mid, s))
    for mid, s in plan:
        con.execute("update metric set synonyms=? where id=?", (s, mid))
    return [f"«Она же» записано: {len(plan)} (уже стояло {len(SINONIMY) - len(plan)})"]


def proverit(con):
    """Список претензий. Пустой список — всё чисто."""
    pretenzii = []
    for mid, s in SINONIMY.items():
        r = con.execute("select synonyms from metric where id=?", (mid,)).fetchone()
        if not r or r[0] != s:
            pretenzii.append(f"⛔ mid {mid}: «Она же» не «{s}»")
    # правило 26.09: у новой карточки «Она же» не пусто; после этой миграции пустых нет нигде
    for mid, name in con.execute("select id, name from metric where synonyms is null or trim(synonyms)=''"):
        pretenzii.append(f"⛔ mid {mid} «{name}»: пустое «Она же»")
    # новый синоним не совпадает ни с именем, ни с синонимом другой метрики
    chuzhie = {}
    for mid, name, syn in con.execute("select id, name, coalesce(synonyms,'') from metric"):
        for t in [name] + re.split(r"[;,]\s*", syn):
            if t.strip():
                chuzhie.setdefault(norm(t), set()).add(mid)
    for mid, s in SINONIMY.items():
        drugie = chuzhie.get(norm(s), set()) - {mid}
        if drugie:
            pretenzii.append(f"⛔ mid {mid}: «{s}» стоит и у {sorted(drugie)}")
        if "—" in s or re.search(r"\bкотор", s):
            pretenzii.append(f"⛔ mid {mid}: в синониме тире или «который»")
    return pretenzii


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    put = pathlib.Path(sys.argv[1]).resolve()
    if not put.exists():
        sys.exit(f"✖ базы нет: {put}")
    con = sqlite3.connect(put)
    if "--check" not in sys.argv:
        metka = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
        kopiya = put.with_name(f"{put.stem}.before_010_{metka}{put.suffix}")
        shutil.copy2(put, kopiya)
        print(f"бэкап: {kopiya.name}")
        for s in primenit(con):
            print("  " + s)
        con.commit()
    pretenzii = proverit(con)
    if pretenzii:
        print(f"\nпретензий: {len(pretenzii)}")
        for p in pretenzii:
            print(" ", p)
        sys.exit(1)
    print("проверка: чисто")


if __name__ == "__main__":
    main()
