def primenit(con):
    """Сначала сверяет все правки, потом пишет. Возвращает отчёт строками."""
    otchet, plan = [], []
    for mid, (bylo, stalo) in IMENA.items():
        imya = con.execute("select name from metric where id=?", (mid,)).fetchone()
        if not imya:
            sys.exit(f"✖ mid {mid} нет в базе")
        if imya[0] == stalo:
            continue
        if imya[0] != bylo:
            sys.exit(f"✖ mid {mid}: имя «{imya[0]}», ждали «{bylo}» — ничего не пишу")
        plan.append((mid, "name", bylo, stalo))
    tekst = {}
    for mid, pole, bylo, stalo in PRAVKI:
        t = tekst.get((mid, pole))
        if t is None:
            r = con.execute(f"select {pole} from metric where id=?", (mid,)).fetchone()
            if not r:
                sys.exit(f"✖ mid {mid} нет в базе")
            t = r[0] or ""
        n = t.count(bylo)
        if n == 0 and stalo in t:
            continue
        if n != 1:
            sys.exit(f"✖ mid {mid}, {pole}: «{bylo[:60]}…» встречается {n} раз — ничего не пишу")
        tekst[(mid, pole)] = t.replace(bylo, stalo)
        plan.append((mid, pole, bylo, stalo))
    art = con.execute("select id from artifact where slug=? and type='tree'", (SLUG,)).fetchone()
    if not art:
        sys.exit(f"✖ дерева «{SLUG}» нет в базе")
    q = con.execute("select id, question from metric_artifact where artifact_id=? and metric_id=945", (art[0],)).fetchone()
    if not q:
        sys.exit("✖ в дереве LTV нет места 945")
    if q[1] not in VOPROS_945:
        sys.exit(f"✖ вопрос у 945: «{q[1]}», ждали «{VOPROS_945[0]}» — ничего не пишу")

    for mid, pole, bylo, stalo in plan:
        if pole == "name":
            con.execute("update metric set name=? where id=?", (stalo, mid))
            otchet.append(f"{mid}: имя «{bylo}» → «{stalo}»")
    for (mid, pole), t in tekst.items():
        con.execute(f"update metric set {pole}=? where id=?", (t, mid))
    n_tekst = sum(1 for p in plan if p[1] != "name")
    otchet.append(f"правок в текстах: {n_tekst} (уже стояло {len(PRAVKI) - n_tekst})")
    if q[1] != VOPROS_945[1]:
        con.execute("update metric_artifact set question=? where id=?", (VOPROS_945[1], q[0]))
        otchet.append("945: в вопрос дерева дописан невыкуп")
    return otchet


def proverit(con):
    """Список претензий. Пустой список — всё чисто."""
    pretenzii = []
    for mid, (bylo, stalo) in IMENA.items():
        imya = con.execute("select name from metric where id=?", (mid,)).fetchone()
        if not imya or imya[0] != stalo:
            pretenzii.append(f"⛔ mid {mid}: имя не «{stalo}»")
    # старые имена не должны остаться нигде, ни в одной форме
    starye = [re.compile(p) for p in (
        r"[Зз]атрат\w* на инфраструктуру и сторонние сервисы на аккаунт", r"[Зз]атрат\w* на поддержку на (аккаунт|заказ)",
        r"[Зз]атрат\w* на сопровождение клиентов на аккаунт", r"[Чч]ист\w+ затрат\w* на доставку на заказ",
        r"[Зз]атрат\w* на возвраты и невыкуп на заказ", r"(на покупателя|[Зз]аказ\w*|[Вв]изит\w*) в месяц жизни")]
    for r in con.execute(f"select id, {', '.join(POLYA)} from metric"):
        for pole, t in zip(POLYA, r[1:]):
            for p in starye:
                if t and p.search(t):
                    pretenzii.append(f"⛔ mid {r[0]}, {pole}: осталось старое имя «{p.search(t).group(0)}»")
    for mid, nm in con.execute("select id, name from metric"):
        if len(re.findall(r"\bна\b", nm)) >= 2:
            pretenzii.append(f"⛔ mid {mid}: в имени два «на» — «{nm}»")
    # обороты, которые этой миграцией убраны из новых карточек
    for r in con.execute(f"select id, {', '.join(POLYA)} from metric where id between 928 and 955"):
        t = " ".join(x or "" for x in r[1:])
        for p, chto in ((r"по построению", "«по построению»"), (r"\bкук[аеуо]\b", "«кука»"), (r"\bнеузнан", "«неузнан» слитно"),
                        (r"\bсмес[ьи] заказ", "«смесь заказов»"), (r"раньше по пути", "«раньше по пути»")):
            if re.search(p, t):
                pretenzii.append(f"⛔ mid {r[0]}: остался оборот {chto}")
        if r[0] in (947, 948, 953) and re.search(r"\b[Жж]ив(ой|ым|ые|ых|ая|ую)\b", t):
            pretenzii.append(f"⛔ mid {r[0]}: остался «живой покупатель»")
        if "—" in t:
            pretenzii.append(f"⛔ mid {r[0]}: длинное тире")
    q = con.execute("""select pa.question from metric_artifact pa join artifact a on a.id = pa.artifact_id
                       where a.slug=? and pa.metric_id=945""", (SLUG,)).fetchone()
    if not q or q[0] != VOPROS_945[1]:
        pretenzii.append("⛔ у 945 в вопросе дерева нет невыкупа")
    return pretenzii


