def svesti(con, otchet):
    for ubrat, ostavit in SVESTI.items():
        if not con.execute("select 1 from metric where id=?", (ubrat,)).fetchone():
            otchet.append(f"{ubrat} уже сведена в {ostavit}")
            continue
        imya_u, imya_o = (con.execute("select name from metric where id=?", (m,)).fetchone()[0]
                          for m in (ubrat, ostavit))
        if imya_u != imya_o:
            sys.exit(f"✖ сводим разные имена: {ubrat} «{imya_u}» и {ostavit} «{imya_o}»")
        n = con.execute("update metric_artifact set metric_id=? where metric_id=?",
                        (ostavit, ubrat)).rowcount
        # разрез, который есть у обеих, остаётся с заметкой оставшейся
        con.execute("update or ignore metric_dimension set metric_id=? where metric_id=?", (ostavit, ubrat))
        con.execute("delete from metric_dimension where metric_id=?", (ubrat,))
        con.execute("update question set metric_id=? where metric_id=?", (ostavit, ubrat))
        # связь метрики с самой собой не бывает
        sam = con.execute("""delete from metric_metric where id in (
                               select e.id from metric_metric e
                               join metric_artifact s on s.id = e.source_id
                               join metric_artifact t on t.id = e.target_id
                               where s.metric_id = t.metric_id)""").rowcount
        con.execute("delete from metric where id=?", (ubrat,))
        otchet.append(f"«{imya_o}»: {ubrat} → {ostavit}, мест перешло {n}"
                      + (f", снято связей с собой {sam}" if sam else ""))
    for mid, polya in KARTOCHKI.items():
        for pole, tekst in polya.items():
            con.execute(f"update metric set {pole}=? where id=?", (tekst, mid))


def pereimenovat(con, otchet):
    n = 0
    for mid, (bylo, stalo) in IMENA.items():
        r = con.execute("select name from metric where id=?", (mid,)).fetchone()
        if not r:
            sys.exit(f"✖ метрики {mid} нет")
        if r[0] == stalo:
            continue
        if r[0] != bylo:
            sys.exit(f"✖ {mid} называется «{r[0]}», ожидалось «{bylo}» — кто-то уже правил")
        con.execute("update metric set name=? where id=?", (stalo, mid))
        n += 1
    otchet.append(f"переименовано метрик: {n} из {len(IMENA)}")
    r = con.execute("update artifact set name=? where slug=? and type='tree' and name=?",
                    (DEREVO_STALO, DEREVO_SLUG, DEREVO_BYLO)).rowcount
    otchet.append(f"дерево «{DEREVO_BYLO}» → «{DEREVO_STALO}»" if r else "дерево уже переименовано")


