def proverit(con):
    pr = []
    imya_r, _, stalo_r = RAZREZ
    if con.execute("select description, variants from dimension where name=?", (imya_r,)).fetchone() != stalo_r:
        pr.append(f"⛔ разрез «{imya_r}» не тот")
    uzly = {r[0] for r in con.execute("select node_id from metric_artifact where node_id is not null")}
    uzly |= {"spravochnik/" + r[0] for r in con.execute("select slug from metric")}

    novye = json.loads(DANNYE.read_text(encoding="utf-8"))
    polya = ["name", "slug", "unit", "formula", "description", "nuances", "example", "importance", "not_needed",
             "en", "synonyms", "essence", "essence_note"]
    for m in novye:
        r = con.execute(f"select {', '.join(polya)} from metric where id=?", (m["id"],)).fetchone()
        if not r:
            pr.append(f"⛔ mid {m['id']} нет в базе")
            continue
        for p, v in zip(polya, r):
            if v != m[p]:
                pr.append(f"⛔ mid {m['id']}.{p} не как в файле")
        razr = con.execute("""select md.priority, d.name, md.note from metric_dimension md
                              join dimension d on d.id = md.dimension_id where md.metric_id=? order by md.priority""",
                           (m["id"],)).fetchall()
        if razr != [(d["priority"], d["name"], d["note"]) for d in m["dims"]]:
            pr.append(f"⛔ mid {m['id']}: разрезы не как в файле")
        vopr = con.execute("select group_id, text from question where metric_id=? order by priority",
                           (m["id"],)).fetchall()
        if vopr != [(q["group"], q["text"]) for q in m["questions"]]:
            pr.append(f"⛔ mid {m['id']}: вопросы не как в файле")
        for p in ("formula", "description", "nuances", "example", "importance", "not_needed"):
            for adres in SSYLKA.findall(m[p]):
                if adres not in uzly:
                    pr.append(f"⛔ mid {m['id']}.{p}: ссылка в никуда {adres}")
            if "—" in m[p]:
                pr.append(f"⛔ mid {m['id']}.{p}: длинное тире")
        if any("—" in q["text"] for q in m["questions"]):
            pr.append(f"⛔ mid {m['id']}: длинное тире в вопросах")

    for mid, imya, pole, bylo, stalo, punkt in TSELIKOM:
        t, est = tekst(con, mid, imya, pole)
        if not est or (t or None) != (stalo or None):
            pr.append(f"⛔ {punkt} {mid}.{pole}: не новый текст")
    for mid, imya, pole, bylo, stalo, punkt in PRAVKI:
        t, est = tekst(con, mid, imya, pole)
        if not est or stalo not in (t or ""):
            pr.append(f"⛔ {punkt} {mid}.{pole}: новой правки нет")
        elif not stalo.startswith(bylo) and bylo in (t or ""):
            pr.append(f"⛔ {punkt} {mid}.{pole}: старый текст остался")
    for mid, imya, pole, _, stalo, punkt in TSELIKOM + PRAVKI:
        for adres in SSYLKA.findall(stalo):
            if adres not in uzly:
                pr.append(f"⛔ {punkt} {mid}.{pole}: ссылка в никуда {adres}")
        if "—" in stalo:
            pr.append(f"⛔ {punkt} {mid}.{pole}: длинное тире")
    for mid, n, _, stalo, punkt in VOPROSY:
        r = con.execute("select text from question where metric_id=? and priority=?", (mid, n)).fetchone()
        if not r or r[0] != stalo:
            pr.append(f"⛔ {punkt} вопрос {n} у {mid}: не новый текст")

    aid = con.execute("select id, access, family_id from artifact where slug=?", (SLUG,)).fetchone()
    if not aid:
        return pr + ["⛔ артефакта дерева нет"]
    aid = aid[0]
    mesta = con.execute("""select metric_id, role, y, is_key, question, node_id from metric_artifact
                           where artifact_id=?""", (aid,)).fetchall()
    nado = {(mid, rol, float(y), int(rol == "key"), vopros) for mid, rol, y, _, _, vopros in UZLY}
    if {m[:5] for m in mesta} != nado:
        pr.append(f"⛔ места дерева не как в UZLY: {len(mesta)} против {len(nado)}")
    rebra = set(con.execute("""select ms.metric_id, mt.metric_id, e.sign, e.type from metric_metric e
                               join metric_artifact ms on ms.id = e.source_id
                               join metric_artifact mt on mt.id = e.target_id
                               where ms.artifact_id=? or mt.artifact_id=?""", (aid, aid)).fetchall())
    nado_r = {(mid, rod, znak, tip) for mid, _, _, roditeli, _, _ in UZLY for rod, znak, tip in roditeli}
    if rebra != nado_r:
        pr.append(f"⛔ рёбра дерева не как в UZLY: лишние {rebra - nado_r}, нет {nado_r - rebra}")
    if {(s, t) for s, t, _, tip in nado_r if tip == A and s != 965} != TOZHDESTVA_ALT:
        pr.append("⛔ тождества дерева разошлись с выдачей скрипта по alt_formula")
    for mid, _, _, roditeli, _, _ in UZLY:
        sut = con.execute("select essence from metric where id=?", (mid,)).fetchone()[0]
        for rod, znak, _ in roditeli:
            sut_rod = con.execute("select essence from metric where id=?", (rod,)).fetchone()[0]
            if sut_rod != "больше-лучше" or sut not in ("больше-лучше", "меньше-лучше") or (mid, rod) in ZNAK_PROTIV_SUTI:
                continue
            if (znak == "+") != (sut == "больше-лучше"):
                pr.append(f"⛔ {mid} → {rod}: знак {znak}, а суть «{sut}»")
    # вопрос дерева (миграция 008): у каждого места, с «?», без разметки, у соседей разные
    for mid, rol, _, _, vopros, nid in mesta:
        if not vopros or not vopros.endswith("?") or re.search(r"\*\*|\[\[|<", vopros):
            pr.append(f"⛔ вопрос у места {nid} не годится")
    return pr


