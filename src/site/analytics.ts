// Аналитика поведения внутри Атласа.
//
// Зачем: карты считаются Метрикой сами (каждая карта — отдельная страница Тильды),
// а всё, что происходит ВНУТРИ карты, счётчик не видит: открытие карточки метрики —
// это состояние React, адрес правится через history.replaceState, а он просмотра
// не порождает. Поэтому события отправляем руками.
//
// Приложение только СООБЩАЕТ о событии и ничего не знает про счётчик: номер счётчика
// и решение, что с событием делать, живут на родительской странице Тильды. Так номер
// лежит в одном месте, а не в двух сборках.
//
// Протокол (расширяет уже работающий мост jmAtlasReady/jmAtlasEmail):
//   iframe → parent: { type: 'jm-atlas-event', ... }
// Родитель зовёт ym(<счётчик>, 'hit', path, { title }).
//
// План и договорённости — ../../analytics_plan.md

/** Версия схемы события: если формат поменяется, родитель сможет отличить старое от нового. */
const SCHEMA = 1

/** Включает лог событий в консоль: ?jmdebug=1 в адресе. Для проверки без Метрики. */
const DEBUG = typeof window !== 'undefined' && /[?&]jmdebug=1/.test(window.location.search)

export type MetricAction = 'metric_open' | 'metric_view'

export interface MetricEvent {
  type: 'jm-atlas-event'
  v: number
  action: MetricAction
  /** Адрес виртуального просмотра: /atlas/<слаг карты>/<слаг метрики>/<ключ вкладки>. */
  path: string
  /** Человеческий заголовок для отчёта «Заголовки страниц». */
  title: string
  section: string
  nodeId: string
  tab: string
}

interface NodeLike { id: string; name: string; section: string }

function send(ev: MetricEvent) {
  if (DEBUG) console.log('[jm-atlas-event]', ev.action, ev.path, ev)
  try {
    // Родителя нет (открыли сборку напрямую, локальная разработка) — отправлять некому.
    if (window.parent === window.self) return
    window.parent.postMessage(ev, '*')
  } catch {
    /* родитель недоступен — аналитика не повод ронять карточку */
  }
}

/**
 * Событие по метрике.
 *
 * Два вида:
 *   metric_open — метрику открыли (отрезок `_open`);
 *   metric_view — вкладку показали (отрезок = ключ вкладки). Шлётся и когда первая
 *                 вкладка показалась сама при открытии, и на каждый клик по вкладке.
 *
 * Открытие метрики порождает ОБА события: `_open` и показ первой вкладки. Так строка
 * отчёта по любой вкладке означает «сколько раз вкладку показали», и три вкладки
 * сравнимы между собой напрямую, без сложений. Решение Марии 25.08.
 *
 * ВАЖНО: `tabKey` и `tabLabel` приходят из данных вкладок (массив TABS в NodeCard),
 * а не из списка внутри этого файла. Добавили вкладку в TABS — она считается сама.
 * Любое перечисление вида «если calc, то...» здесь приведёт к тому, что новая вкладка
 * тихо выпадет из статистики.
 *
 * Ключ вкладки — технический (`essence`), а не подпись («Суть»): подпись могут
 * переименовать, и тогда история разъедется на два несравнимых куска.
 */
export function trackMetric(
  action: MetricAction,
  node: NodeLike,
  tabKey: string,
  tabLabel: string,
) {
  // node.id уже вида "<слаг карты>/<слаг метрики>" и латиницей. Кириллица в адресе
  // показывалась бы в отчёте Метрики как %D0%A4%D0%B8... — читать невозможно.
  // Этот же id — первичный ключ контента и правок (atlas_content.json, fixes.json),
  // поэтому переименование метрики его не меняет: история не разъедется.
  // До счётчика доезжает ТОЛЬКО путь: поле `action` остаётся внутри сообщения.
  // Поэтому открытие метрики и показ вкладки обязаны идти разными адресами, иначе
  // в отчёте склеятся в одну строку.
  //
  // Подчёркивание в `_open` — чтобы отрезок никогда не столкнулся с ключом будущей
  // вкладки: ключи вкладок подчёркиванием не начинаются.
  const isOpen = action === 'metric_open'
  const slot = isOpen ? '_open' : tabKey
  const slotLabel = isOpen ? 'Открытие' : tabLabel

  const ev: MetricEvent = {
    type: 'jm-atlas-event',
    v: SCHEMA,
    action,
    path: `/atlas/${node.id}/${slot}`,
    title: `${node.section} / ${node.name} / ${slotLabel}`,
    section: node.section,
    nodeId: node.id,
    tab: tabKey,
  }
  send(ev)
}
