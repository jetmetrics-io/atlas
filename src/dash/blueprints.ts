// Цвет кодирует СОСТОЯНИЕ метрики, а не её важность: ухудшилась — коралловый,
// улучшилась — зелёный, стоит на месте — серый. Ключевая помечается словом, а не цветом.
export type Tone = 'bad' | 'good' | 'flat'

export type Metric = {
  id: string // id узла Атласа — по нему блок связан с картой
  name: string // дословно из карты
  value: string
  delta: string // всегда в процентах к началу периода
  tone: Tone
  series: number[]
  dom?: [number, number] // общая шкала для метрик одной природы
  thr?: number // норматив пунктиром — только если он есть в карте отдельным узлом
  thrLabel?: string
  // Прогнозный узел карты не становится блоком-причиной: прогноз не вызывает факт.
  // Он ложится пунктиром на линию самого факта — расхождение и есть диагностическая
  // величина, а мерит её отдельная метрика карты («Точность прогноза»).
  ghost?: number[]
  ghostLabel?: string
  ghostId?: string // id прогнозного узла — чтобы блок подсвечивал его на карте
  unit?: string
  isKey?: boolean
  tip: Tip
}

// Направление метрики: рост — это хорошо или плохо. Нужно, чтобы цвет нёс ЗНАК, а не модуль
// (Д6.2). Раскраска «сильно изменилось = красный» делает улучшение невыразимым.
export type Dir = 'up-good' | 'up-bad' | 'none'

// Цвет дельты считается из направления метрики, а не из величины изменения.
// Порог «не менялось» — два процента: на недельной корзине меньшее движение неотличимо
// от шума, а покрашенный шум съедает внимание, которое нужно настоящему провалу.
export function toneOf(delta: number, dir: Dir): Tone {
  if (dir === 'none' || Math.abs(delta) < 2) return 'flat'
  return (delta > 0) === (dir === 'up-good') ? 'good' : 'bad'
}

export const pct = (x: number) => (x > 0 ? '+' : x < 0 ? '−' : '') + Math.abs(x) + '%'

// Д6.3b: две ступени ухудшения. До 2% — серое, 2–15% — цвет на шрифте дельты,
// больше 15% — плюс заливка плитки. Заливка говорит «здесь плохо» на фоне листа,
// где покрасневших метрик много, а шрифт один их не различает.
// Насколько сильно метрика сдвинулась. Нужно, чтобы выбрать ОДНУ плитку под заливку.
export function shift(delta: string, tone: Tone): number {
  if (tone === 'flat') return 0
  const m = delta.replace(',', '.').match(/[\d.]+/)
  return m ? Math.abs(parseFloat(m[0])) : 0
}

// Заливку получает ровно одна плитка — та, что сдвинулась сильнее всех, и только если
// сдвиг заметный. Раньше её получала каждая метрика с изменением больше 15%: заливались
// пять плиток из семи, и цвет переставал что-либо значить (Д6.4 против Д6.3b, § 26 вопрос 15).
// Аларм на пяти плитках — не аларм, а фон.
export function alarmId(ms: { id: string; delta: string; tone: Tone }[]): string | null {
  let best: string | null = null, top = 25
  for (const m of ms) {
    const v = shift(m.delta, m.tone)
    if (v > top) { top = v; best = m.id }
  }
  return best
}

// Разрез «где именно просело». В модели карты разрезов нет — это дыра, закрытая руками.
// Строка держит три величины: метрику вершины, выбранную метрику и объём. У каждой —
// своё изменение за период. Объём обязателен (Д3.4): −22% на 40 обращениях и на 2 070 —
// разные разговоры. База (anket) обязательна для опросных метрик (Д3.5).
export type CutRow = {
  label: string
  top: string; dTop: number // метрика вершины
  sel: string; dSel: number // выбранная переключателем
  vol: string; dVol: number // объём
  base?: string // сколько анкет под расчётом — только для опросных метрик (Д3.5)
  // Доля ответивших. Без неё колонка базы говорит «данных мало», но не говорит главного:
  // отвечают не все и не случайно, и доля ответивших сама меняется по каналу. Сравнение
  // строк тогда — отчасти сравнение двух разных машин отбора, а не качества работы.
  resp?: string
  // Ячейка ниже порога доверия (100 анкет): значение показываем, выводов не делаем.
  // Приглушается только оценка — объём и время считаются по всем обращениям, они целы.
  weak?: boolean
  // Спарклайн вершины. НЕобязателен: Д5.2 снято 12.08.2026 — «когда сломалось» закрывается
  // динамикой наверху листа, там это видно лучше, чем в шестнадцати микрографиках. Остаётся
  // допустимым приёмом, когда разрез сам несёт сюжет во времени. Нет ни у одной строки —
  // колонка «Тренд» не рисуется.
  series?: number[]
  worst?: boolean
}

export type CutBlock = {
  title: string
  col: string // заголовок первой колонки
  hint?: string
  rows: CutRow[]
  tip: Tip
}

// Переключатель метрики для разрезов. Выбранная печатается в шапке каждой таблицы (Д8.8):
