export function tilesOf(b: Blueprint): Metric[] {
  return [b.vertex, ...b.causes, ...b.deeper]
}

// Узлы карты, которые лист занял. Кроме блоков сюда входят прогнозные узлы: блоком они
// не стоят, но на листе присутствуют пунктиром — на карте их гасить нельзя.
export function litNodesOf(b: Blueprint): string[] {
  const t = tilesOf(b)
  return [...t.map((m) => m.id), ...t.flatMap((m) => (m.ghostId ? [m.ghostId] : []))]
}
